"""Native zsh completion generated from the CLI's parsers and field registries."""
from __future__ import annotations

import argparse
import shlex
import sys

from brewq import columns, options


def _option_specs(parser: argparse.ArgumentParser) -> str:
    specs = []
    for action in parser._actions:
        if not action.option_strings:
            continue
        aliases = " ".join(action.option_strings)
        description = action.help if action.help != argparse.SUPPRESS else action.dest.replace("_", " ")
        description = (description or "").replace("[", "").replace("]", "")
        argument = ""
        if action.nargs != 0:
            if action.dest == "sort":
                argument = f":sort field:({' '.join(options.SORT_CHOICES)})"
            elif action.dest == "columns":
                argument = ":columns:_brewq_column_list"
            else:
                argument = ":number:"
        for flag in action.option_strings:
            suffix = ("=" if flag.startswith("--") else "+") if argument else ""
            specs.append(shlex.quote(f"({aliases}){flag}{suffix}[{description}]{argument}"))
    return " ".join(specs)


def zsh_script(search: argparse.ArgumentParser, commands: argparse.ArgumentParser) -> str:
    subparsers = next(
        action for action in commands._actions if isinstance(action, argparse._SubParsersAction)
    ).choices
    branches = []
    positional = {"+config": "'1:action:(path)'", "+completion": "'1:shell:(zsh)'"}
    for name, parser in subparsers.items():
        branches.append(
            f"      {shlex.quote(name)}) _arguments -s -S {_option_specs(parser)} {positional.get(name, '')} ;;"
        )
    # Bind to the generating environment, not a possibly older executable on PATH.
    backend = shlex.join([sys.executable, "-I", "-m", "brewq.cli", "--_complete"])
    fields = " ".join((*columns.CANONICAL_COLUMNS, "30d", "90d", "365d", "trend", "bin", "desc", "home"))
    command_names = " ".join(
        shlex.quote(name) for name in (*subparsers, "+refresh", "+update-cache")
    )
    command_pattern = "|".join(
        shlex.quote(name) for name in (*subparsers, "+refresh", "+update-cache")
    )
    return f'''#compdef brewq bq
# Generated by brewq completion zsh; regenerate after moving its Python environment.
_brewq_columns() {{
  local -a fields=({fields})
  compset -P '[+-]'
  _describe column fields "$@"
}}
_brewq_column_list() {{
  compset -P '='
  if [[ $PREFIX != [+-]* && $PREFIX != *,* ]]; then
    local -a selections=(all default help)
    _describe 'column selection' selections
  fi
  _sequence -s , _brewq_columns
}}
_brewq_packages() {{
  local -a names commands=({command_names})
  (( CURRENT == 2 )) && _describe command commands
  names=("${{(@f)$({backend} 2>/dev/null)}}")
  names=("${{(@)names:#}}")
  (( $#names )) && compadd -a names
}}
_brewq() {{
  local -a words=("${{words[@]}}")
  local CURRENT=$CURRENT
  if (( CURRENT > 2 )) && [[ $words[2] == ({command_pattern}) ]]; then
    local subcommand=$words[2]
    [[ $subcommand == '+update-cache' || $subcommand == '+refresh' ]] && subcommand=+update
    words=("$words[1] $subcommand" "${{words[@]:2}}")
    (( CURRENT-- ))
    case $subcommand in
{chr(10).join(branches)}
    esac
  else
    _arguments -s -S {_option_specs(search)} '*:package:_brewq_packages'
  fi
}}
compdef _brewq brewq bq
'''
